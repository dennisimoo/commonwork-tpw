import assert from 'node:assert/strict';
import {defaultFields,validateFields,customValues,duplicateMatches,exportActivityRows} from '../public/report-fields.mjs';
import {toCSV} from '../public/core.mjs';
const config=defaultFields(),id='custom_12345678-1234-1234-1234-123456789abc';
config.fields.push({id,label:'Staff hours',type:'number',active:true,required:true});
assert.throws(()=>customValues({},config,true),/required/);
const textConfig={fields:[{id,type:'text',label:'Required note',required:true,active:true}]};
assert.throws(()=>customValues({custom_fields:{[id]:'   '}},textConfig,true),/required/);
assert.throws(()=>customValues({custom_fields:{[id]:-1}},config),/non-negative/);
assert.throws(()=>validateFields(config.fields.slice(1),config),/archiving/);
assert.throws(()=>validateFields(config.fields.map(f=>f.id===id?{...f,type:'text'}:f),config),/new field/);
const row={id:'a',program:'Course',facility:'Prison',yard:'A',start_date:'2025-11-01',end_date:'2026-01-01',program_hours:10,completions:0,custom_fields:{[id]:2}};
assert.equal(duplicateMatches([row],[row]).length,0);
assert.equal(duplicateMatches([{...row,id:undefined,program:'  COURSE '}],[row]).length,1);
assert.equal(duplicateMatches([{...row,id:undefined,yard:'B'}],[row]).length,0);
assert.equal(duplicateMatches([{...row,start_date:null}],[row]).length,0);
const batch=[{...row,id:undefined},{...row,id:undefined}];assert.equal(duplicateMatches(batch,batch)[0].matches,1);
const exported=exportActivityRows([row,{...row,completions:null,program:'=1+1'}],config);
assert.equal(exported[0].program_year,2025);assert.equal(exported[0].total_participant_hours_delivered,0);assert.equal(exported[1].total_participant_hours_delivered,'');assert.equal(exported[0][`Staff hours [${id}]`],2);
assert.ok(toCSV(exported).includes("'=1+1"));assert.ok(!toCSV(exported).includes('[object Object]'));
console.log('PASS: field validation, duplicate matching and standardized CSV calculations including zero, missing values and formula escaping.');
